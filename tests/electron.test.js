const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { promisify } = require('node:util');
const { execFile } = require('node:child_process');
const { _electron } = require('playwright-core');
const JSZip = require('jszip');
const XLSX = require('xlsx');

test('native workspace: mixed QA, safe preview, exports, clearing and silent video', { timeout: 120000 }, async () => {
    const root = path.resolve(__dirname, '..');
    const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'creative-qa-test-'));
    const profileDirectory = path.join(directory, 'profile');
    await fs.mkdir(profileDirectory);
    const environment = { ...process.env };
    delete environment.ELECTRON_RUN_AS_NODE;
    const app = await _electron.launch({ args: [path.join(root, 'main.js'), `--user-data-dir=${profileDirectory}`], env: environment });
    try {
        assert.equal(await app.evaluate(({ app }) => app.getPath('userData')), profileDirectory);
        const page = await app.firstWindow();
        const errors = [];
        page.on('pageerror', error => errors.push(error.message));
        await page.waitForSelector('#run-all');
        assert.equal(await page.evaluate(() => typeof window.electronAPI.analyzeVideo), 'function');
        await page.evaluate(() => { localStorage.clear(); localStorage.setItem('sunshine-settings', JSON.stringify({ reviewer: 'Legacy name', 'spec-name': 'Saved specification' })); });
        await page.reload();
        assert.equal(await page.locator('#reviewer').count(), 0);
        assert.equal(await page.locator('#profile').count(), 0);
        assert.equal(await page.locator('#display-reference').inputValue(), 'Saved specification');
        assert.equal(await page.evaluate(() => Object.hasOwn(JSON.parse(localStorage.getItem('sunshine-settings')), 'reviewer')), false);
        const png = Buffer.from(await page.evaluate(() => { const canvas = document.createElement('canvas'); canvas.width = 300; canvas.height = 250; const context = canvas.getContext('2d'); context.fillStyle = '#f2ce2b'; context.fillRect(0, 0, 300, 250); return canvas.toDataURL('image/png').split(',')[1]; }), 'base64');
        const zip = new JSZip();
        zip.file('index.html', '<!doctype html><html><head><meta charset="UTF-8"><meta name="ad.size" content="width=300,height=250"><link rel="stylesheet" href="css/style.css"></head><body><button id="exit">Click creative</button><a id="jslink" href="javascript:window.open(window.clickTag)">Link</a><button id="nav">Nav</button><button id="enab">Enabler</button><script src="click.js"></script></body></html>');
        zip.file('click.js', 'var clickTag="https://example.com/landing"; document.getElementById("exit").onclick=function(){window.open(clickTag)}; window.Enabler={exit:function(){}}; document.getElementById("nav").onclick=function(){location.href="https://example.com/nav"}; document.getElementById("enab").onclick=function(){Enabler.exit("Hero")};');
        zip.file('css/style.css', 'body{margin:0;width:300px;height:250px;background:url(../images/bg.png)}');
        zip.file('images/bg.png', png);
        const validZip = await zip.generateAsync({ type: 'nodebuffer' });
        const badZip = new JSZip();
        badZip.file('index.html', '<meta name="ad.size" content="width=300,height=250"><script>/* var clickTag="https://example.com";window.open(clickTag); */</script>');
        const mixedVideo = path.join(directory, 'mixed.mp4');
        const mixedAudio = path.join(directory, 'mixed.wav');
        await promisify(execFile)(path.join(root, 'ffmpeg', 'ffmpeg.exe'), ['-hide_banner', '-loglevel', 'error', '-f', 'lavfi', '-i', 'color=c=yellow:s=320x240:d=1', '-f', 'lavfi', '-i', 'sine=frequency=1000:duration=1', '-shortest', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-c:a', 'aac', mixedVideo]);
        await promisify(execFile)(path.join(root, 'ffmpeg', 'ffmpeg.exe'), ['-hide_banner', '-loglevel', 'error', '-f', 'lavfi', '-i', 'sine=frequency=1000:duration=1', mixedAudio]);
        const inputs = [
            { name: 'campaign-300x250.zip', mimeType: 'application/zip', buffer: validZip },
            { name: 'commented-click.zip', mimeType: 'application/zip', buffer: await badZip.generateAsync({ type: 'nodebuffer' }) },
            { name: 'backup-300x250.png', mimeType: 'image/png', buffer: png },
            { name: 'truncated.gif', mimeType: 'image/gif', buffer: Buffer.from([71,73,70,56,57,97,1,0,1,0,0,0,0,0x21,0xfe,5]) },
            { name: 'mixed.mp4', mimeType: 'video/mp4', buffer: await fs.readFile(mixedVideo) },
            { name: 'mixed.wav', mimeType: 'audio/wav', buffer: await fs.readFile(mixedAudio) }
        ];
        await page.locator('#allFiles').setInputFiles(inputs);
        await page.locator('#run-all').click();
        await page.waitForFunction(() => document.getElementById('run-status').textContent.startsWith('Preflight complete'));
        assert.equal(await page.locator('#total-count').textContent(), '6');
        assert.equal(await page.locator('#failed-count').textContent(), '4');
        assert.equal(await page.locator('#review-count').textContent(), '1');
        assert.match(await page.locator('#checks').textContent(), /Click destination/);
        await page.locator('#preview-tab').click();
        await page.getByRole('button', { name: 'Load preview' }).click();
        await page.waitForSelector('#preview-stage iframe');
        const frame = page.frameLocator('#preview-stage iframe');
        await frame.locator('#exit').click();
        await page.waitForFunction(() => document.getElementById('runtime-events').textContent.includes('example.com/landing'));
        await frame.locator('#jslink').click();
        await frame.locator('#enab').click();
        await frame.locator('#nav').click();
        await page.waitForFunction(() => { const text = document.getElementById('runtime-events').textContent; return (text.match(/EXIT/g) || []).length >= 4 && text.includes('Navigation blocked: https://example.com/nav') && text.includes('Enabler.exit(Hero)'); });
        assert.equal(await page.locator('.exit-toast').count(), 1);
        await page.waitForFunction(() => (document.getElementById('runtime-events').textContent.match(/LOADED/g) || []).length >= 2);
        const isolatedFrame = page.frames().find(current => /127\.0\.0\.1/.test(current.url()));
        assert.equal(await isolatedFrame.evaluate(() => typeof window.electronAPI), 'undefined');
        assert.equal(await isolatedFrame.evaluate(() => typeof require), 'undefined');
        assert.equal(await page.locator('#preview-stage iframe').getAttribute('sandbox'), 'allow-scripts');
        await page.locator('#checks-tab').click();
        assert.equal(await page.locator('#preview-stage iframe').count(), 0);
        await page.evaluate(() => {
            const original = URL.createObjectURL;
            URL.createObjectURL = function(blob) { window.__exportBlob = blob; return original.call(this, blob); };
            HTMLAnchorElement.prototype.click = function() {};
        });
        await page.locator('.export-menu summary').click();
        await page.locator('#export-xlsx').click();
        const bytes = await page.evaluate(async () => Array.from(new Uint8Array(await window.__exportBlob.arrayBuffer())));
        const workbook = XLSX.read(Buffer.from(bytes), { type: 'buffer' });
        const rows = XLSX.utils.sheet_to_json(workbook.Sheets['Materials Instructions']);
        assert.equal(rows.length, 6);
        assert.equal(rows.find(row => row['File Type'] === 'WAV')['Creative Type'], 'Audio');
        assert.equal(rows.find(row => row['File Type'] === 'PNG')['Creative Size'], '300x250');
        assert.equal(rows.find(row => row['File Name'] === 'commented-click.zip')['QA Status'], 'Blocked');
        assert.ok(rows[0]['SHA-256']);
        assert.ok(rows.every(row => !Object.hasOwn(row, 'Reviewer')));
        const appliedSpecs = XLSX.utils.sheet_to_json(workbook.Sheets['Applied Specifications']);
        assert.ok(appliedSpecs.every(profile => !Object.hasOwn(profile, 'reviewer')));
        await page.locator('.export-menu summary').click();
        await page.locator('#export-pdf').click();
        await page.waitForFunction(() => window.__exportBlob?.type === 'application/pdf');
        assert.equal(await page.evaluate(async () => (await window.__exportBlob.text()).slice(0, 5)), '%PDF-');
        await page.locator('.export-menu summary').click();
        await page.locator('#export-json').click();
        const evidence = await page.evaluate(async () => JSON.parse(await window.__exportBlob.text()));
        assert.equal(evidence.length, 6);
        assert.equal(evidence[0].profile.version, '2026.10');
        assert.ok(evidence[0].events.some(event => event.kind === 'exit'));
        assert.ok(evidence.every(item => !Object.hasOwn(item, 'reviewedBy') && !Object.hasOwn(item.profile, 'reviewer')));
        const audioEvidence = evidence.find(item => item.kind === 'audio');
        assert.ok(Number.isFinite(audioEvidence.measurement.lufs));
        assert.equal(audioEvidence.profile.width, undefined);
        await page.locator('#type-filter').selectOption('audio');
        assert.equal(await page.locator('#asset-rows tr').count(), 1);
        await page.getByRole('button', { name: 'Inspect mixed.wav' }).click();
        await page.locator('#preview-tab').click();
        assert.equal(await page.locator('#preview-stage audio').count(), 1);
        await page.locator('#checks-tab').click();
        await page.locator('#type-filter').selectOption('all');
        await page.locator('#spec-settings summary').click();
        for (const [id, value] of Object.entries({ 'display-width': '300', 'display-height': '250', 'display-duration': '30', 'image-width': '728', 'image-height': '90', 'image-duration': '10', 'media-width': '320', 'media-height': '240', 'media-duration': '2' })) { await page.locator(`#${id}`).fill(value); await page.locator(`#${id}`).dispatchEvent('change'); }
        await page.getByRole('button', { name: 'Inspect backup-300x250.png' }).click();
        await page.locator('#asset-settings summary').click();
        for (const [id, value] of Object.entries({ 'asset-width': '300', 'asset-height': '250' })) { await page.locator(`#${id}`).fill(value); await page.locator(`#${id}`).dispatchEvent('change'); }
        await page.locator('#run-all').click();
        await page.waitForFunction(() => document.getElementById('run-status').textContent.startsWith('Preflight complete'));
        await page.locator('.export-menu summary').click(); await page.locator('#export-json').click();
        const splitEvidence = await page.evaluate(async () => JSON.parse(await window.__exportBlob.text()));
        assert.equal(splitEvidence.find(item => item.filename === 'campaign-300x250.zip').profile.duration, 30);
        assert.equal(splitEvidence.find(item => item.filename === 'backup-300x250.png').profile.duration, 10);
        assert.equal(splitEvidence.find(item => item.kind === 'video').profile.width, 320);
        assert.equal(splitEvidence.find(item => item.kind === 'audio').profile.width, undefined);
        assert.equal(splitEvidence.find(item => item.filename === 'backup-300x250.png').profile.width, 300);
        assert.equal(await page.locator('#image-width').inputValue(), '728');
        await page.locator('#sort-order').selectOption('type');
        assert.match(await page.locator('#asset-rows tr').first().textContent(), /mixed.wav/);
        await page.setViewportSize({ width: 900, height: 720 });
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
        await page.screenshot({ path: path.join(directory, 'resized-desktop.png'), fullPage: true });
        await page.setViewportSize({ width: 1440, height: 960 });
        await page.screenshot({ path: path.join(directory, 'desktop.png'), fullPage: true });
        await page.locator('#clear-all').click();
        assert.equal(await page.locator('#total-count').textContent(), '0');
        assert.equal(await page.locator('#asset-rows tr').count(), 0);
        assert.equal(await page.locator('#export-xlsx').isDisabled(), true);
        await page.locator('#image-size').fill('200'); await page.locator('#image-size').dispatchEvent('change');
        await page.locator('#image-width').fill('300'); await page.locator('#image-width').dispatchEvent('change');
        await page.locator('#image-height').fill('250'); await page.locator('#image-height').dispatchEvent('change');
        await page.locator('#allFiles').setInputFiles({ name: 'approved.png', mimeType: 'image/png', buffer: png });
        await page.locator('#run-all').click();
        await page.waitForFunction(() => document.getElementById('run-status').textContent.startsWith('Preflight complete'));
        await page.locator('#review-confirmed').check();
        assert.equal(await page.locator('#passed-count').textContent(), '1');
        assert.match(await page.locator('#review-stamp').textContent(), /^Completed \/ /);
        await page.locator('#image-size').fill('1'); await page.locator('#image-size').dispatchEvent('change');
        assert.equal(await page.locator('#export-xlsx').isDisabled(), true);
        await page.locator('#run-all').click();
        await page.waitForFunction(() => document.getElementById('run-status').textContent.startsWith('Preflight complete'));
        await page.locator('#review-confirmed').check();
        assert.equal(await page.locator('#failed-count').textContent(), '1');
        assert.equal(await page.locator('#passed-count').textContent(), '0');
        await page.locator('#clear-all').click();
        await page.locator('#allFiles').setInputFiles(Array.from({ length: 25 }, (_, index) => ({ name: `queued-${index}.png`, mimeType: 'image/png', buffer: png })));
        await page.locator('#run-all').click();
        await page.locator('#cancel-run').click();
        await page.waitForFunction(() => document.getElementById('run-status').textContent.startsWith('Cancelled.'));
        assert.equal(await page.locator('#export-xlsx').isDisabled(), true);
        await page.locator('#clear-all').click();
        const silentVideo = path.join(directory, 'silent.mp4');
        await promisify(execFile)(path.join(root, 'ffmpeg', 'ffmpeg.exe'), ['-hide_banner', '-loglevel', 'error', '-f', 'lavfi', '-i', 'color=c=yellow:s=320x240:d=0.3', '-an', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', silentVideo]);
        const analysis = await page.evaluate(async bytes => window.electronAPI.analyzeVideo(new Uint8Array(bytes).buffer, 'silent.mp4'), [...await fs.readFile(silentVideo)]);
        assert.equal(analysis.metadata.width, 320);
        assert.equal(analysis.metadata.videoCodec, 'h264');
        assert.equal(analysis.audioState, 'No audio track');
        assert.equal(analysis.measurement, null);
        const toneVideo = path.join(directory, 'tone.mp4');
        await promisify(execFile)(path.join(root, 'ffmpeg', 'ffmpeg.exe'), ['-hide_banner', '-loglevel', 'error', '-f', 'lavfi', '-i', 'color=c=yellow:s=320x240:d=1', '-f', 'lavfi', '-i', 'sine=frequency=1000:duration=1', '-shortest', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-c:a', 'aac', toneVideo]);
        await page.locator('.brand').click();
        const tone = await page.evaluate(async bytes => window.electronAPI.analyzeVideo(new Uint8Array(bytes).buffer, 'tone.mp4'), [...await fs.readFile(toneVideo)]);
        assert.ok(Number.isFinite(tone.measurement.lufs));
        assert.ok(Number.isFinite(tone.measurement.truePeak));
        assert.deepEqual(errors, []);
        console.log(`Native screenshots: ${directory}`);
    } finally { await app.close(); }
});